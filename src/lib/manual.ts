/** ค้นหาในคู่มือ คืนหัวข้อที่ตรงกับคำค้น */
export function searchManual(q: string): { chapter: Chapter; topic: Topic }[] {
  const query = q.trim().toLowerCase();
  if (!query) return [];
  const out: { chapter: Chapter; topic: Topic }[] = [];
  for (const c of MANUAL) {
    for (const t of c.topics) {
      const hay = [
        t.title, t.intro, t.forRoles, t.warn ?? "",
        ...(t.steps ?? []).flatMap((s) => [s.do, s.why ?? ""]),
        ...(t.notes ?? []),
      ].join(" ").toLowerCase();
      if (hay.includes(query)) out.push({ chapter: c, topic: t });
    }
  }
  return out;
}

export const MANUAL_TOPIC_COUNT = MANUAL.reduce((a, c) => a + c.topics.length, 0);
